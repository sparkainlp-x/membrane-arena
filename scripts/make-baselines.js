'use strict';
/*
 * Generate baselines.js from the CSV copies in data/.
 *   node scripts/make-baselines.js          write baselines.js
 *   node scripts/make-baselines.js --check  exit 1 when baselines.js is stale
 * Every number the game shows as "measured in the repository" comes from here.
 */
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const SOURCE_COMMIT = 'c74c60beeb9706ea6d30fd6973b2a821a5b23926';
const FILES = {
  contest: ['contest_w32-128_summary.csv', 'contest_256_summary.csv'],
  sweep: ['sweep_summary.csv'],
  stress: ['stress_summary.csv'],
};

function readCsv(name) {
  const text = fs.readFileSync(path.join(root, 'data', name), 'utf8').trim().split(/\r?\n/);
  const head = text[0].split(',');
  return text.slice(1).map((line) => {
    const cells = line.split(',');
    const row = {};
    head.forEach((h, i) => { row[h] = /^-?[\d.]+$/.test(cells[i]) ? Number(cells[i]) : cells[i]; });
    return row;
  });
}

const r1 = (x) => Math.round(x * 10) / 10;

function build() {
  const contest = [].concat(...FILES.contest.map(readCsv));
  const sweep = readCsv(FILES.sweep[0]);
  const stress = readCsv(FILES.stress[0]);
  const at = (rows, width, w, cfg) => rows.find((r) => r.width === width && r.w === w && r.cfg === cfg);
  const widths = [32, 64, 128, 256];

  const CONTEST32 = contest.filter((r) => r.width === 32).map((r) => ({
    w: r.w, cfg: r.cfg, seeds: r.seeds,
    T: r.true_events_mean, Tsd: r.true_events_std, F: r.false_events_mean, Fsd: r.false_events_std,
    P: r.precision_mean, Psd: r.precision_std, rv: r.rate_var_mean, mg: r.max_gain_mean, run: r.runaway_frac,
  }));
  const SCHEMES32 = sweep.filter((r) => r.width === 32 && r.N === 3).map((r) => ({
    scheme: r.scheme, seeds: r.seeds, T: r.true_events_mean, F: r.false_events_mean, P: r.precision_mean,
  }));

  const fpRatios = widths.map((n) => at(contest, n, 0.5, '---').false_events_mean / at(contest, n, 0.5, 'S--').false_events_mean);
  const rvRatios = widths.map((n) => at(contest, n, 0.5, '---').rate_var_mean / at(contest, n, 0.5, 'S--').rate_var_mean);
  const ampDeltas = [];
  for (const n of widths) for (const w of [0, 0.5, 1]) {
    const s = at(contest, n, w, 'S--'), a = at(contest, n, w, 'SA-');
    if (s && a) ampDeltas.push(Math.abs(s.precision_mean - a.precision_mean));
  }
  const stabCosts = widths.map((n) => (at(contest, n, 0.5, 'SA-').precision_mean - at(contest, n, 0.5, 'SAZ').precision_mean) * 100);

  const cells = {};
  for (const r of sweep) (cells[r.width + '/' + r.N] = cells[r.width + '/' + r.N] || []).push(r);
  const cellKeys = Object.keys(cells);
  const indLowest = cellKeys.filter((k) => {
    const rows = cells[k], ind = rows.find((r) => r.scheme === 'individual');
    return rows.every((r) => r === ind || r.true_events_mean > ind.true_events_mean);
  }).length;

  const noZ = stress.filter((r) => !r.cfg.includes('Z')), withZ = stress.filter((r) => r.cfg.includes('Z'));

  const LESSON = {
    shieldFpMin: r1(Math.min(...fpRatios)), shieldFpMax: r1(Math.max(...fpRatios)),
    shieldVarMin: Math.round(Math.min(...rvRatios)), shieldVarMax: Math.round(Math.max(...rvRatios)),
    ampMaxDeltaP: Math.round(Math.max(...ampDeltas) * 1000) / 1000,
    stabCostMin: r1(Math.min(...stabCosts)), stabCostMax: r1(Math.max(...stabCosts)),
    indLowest, indCells: cellKeys.length,
    runawayNoZMin: Math.round(Math.min(...noZ.map((r) => r.runaway_frac)) * 100),
    runawayNoZMax: Math.round(Math.max(...noZ.map((r) => r.runaway_frac)) * 100),
    runawayZMax: Math.round(Math.max(...withZ.map((r) => r.runaway_frac)) * 100),
    seeds: 20,
  };
  const SOURCE = {
    commit: SOURCE_COMMIT,
    repo: 'sparkainlp-x/crystallization-contest',
    contest: 'results/contest_w32-128_summary.csv',
    contest256: 'results/contest_256_summary.csv',
    sweep: 'results/sweep_summary.csv',
    stress: 'results/stress_summary.csv',
  };
  const body = JSON.stringify({ SOURCE, CONTEST32, SCHEMES32, LESSON }, null, 1);
  return [
    '/* GENERATED by scripts/make-baselines.js from data/*.csv. Do not edit by hand. */',
    '(function (root, factory) {',
    "  if (typeof module === 'object' && module.exports) module.exports = factory();",
    '  else root.ArenaBaselines = factory();',
    "})(typeof self !== 'undefined' ? self : this, function () {",
    "  'use strict';",
    '  return ' + body.replace(/\n/g, '\n  ') + ';',
    '});',
    '',
  ].join('\n');
}

if (require.main === module) {
  const out = path.join(root, 'baselines.js'), fresh = build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (cur !== fresh) { console.error('baselines.js is stale: run node scripts/make-baselines.js'); process.exit(1); }
    console.log('baselines.js is current');
  } else { fs.writeFileSync(out, fresh); console.log('wrote baselines.js'); }
}
module.exports = { build, readCsv };
